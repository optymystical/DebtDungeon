    /// <summary>
    /// What a preset leans into. Offense presets put most points into an attack stat;
    /// Defense presets put most into the defensive stat (more max HP and better armor or Shroud use).
    /// </summary>
    public enum PresetRole
    {
        Offense = 0,
        Defense = 1
    }
}
